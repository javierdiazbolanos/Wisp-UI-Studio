/**
 * Generates an individual Screen Composable function.
 */
function generateScreenComposable(screen: ScreenNode): string {
  const fnName = `${toPascalCase(screen.name)}Screen`;
  const isWizard = screen.type === "wizard";
  const totalSteps = screen.steps?.length || Number(screen.props.totalSteps) || 3;

  let code = `@OptIn(ExperimentalMaterial3Api::class)\n`;
  code += `@Composable\n`;
  code += `fun ${fnName}(\n`;
  code += `    onNavigate: (String) -> Unit = {},\n`;
  code += `    onOpenModal: (String) -> Unit = {},\n`;
  code += `    wizardStep: Int = 1,\n`;
  code += `    onStepChange: (Int) -> Unit = {},\n`;
  code += `    formData: MutableMap<String, Any> = remember { mutableStateMapOf() }\n`;
  code += `) {\n`;

  if (isWizard) {
    code += `    Column(\n`;
    code += `        modifier = Modifier\n`;
    code += `            .fillMaxSize()\n`;
    code += `            .verticalScroll(rememberScrollState())\n`;
    code += `            .padding(16.dp),\n`;
    code += `        verticalArrangement = Arrangement.spacedBy(16.dp)\n`;
    code += `    ) {\n`;
    code += `        // Wizard Header & Stepper Card\n`;
    code += `        ElevatedCard(\n`;
    code += `            modifier = Modifier.fillMaxWidth(),\n`;
    code += `            shape = RoundedCornerShape(24.dp),\n`;
    code += `            colors = CardDefaults.elevatedCardColors(\n`;
    code += `                containerColor = MaterialTheme.colorScheme.surfaceContainer\n`;
    code += `            )\n`;
    code += `        ) {\n`;
    code += `            Column(modifier = Modifier.padding(20.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {\n`;
    code += `                Surface(\n`;
    code += `                    shape = RoundedCornerShape(12.dp),\n`;
    code += `                    color = MaterialTheme.colorScheme.primaryContainer,\n`;
    code += `                    contentColor = MaterialTheme.colorScheme.onPrimaryContainer\n`;
    code += `                ) {\n`;
    code += `                    Text(\n`;
    code += `                        text = "WIZARD • PASO $wizardStep DE ${totalSteps}",\n`;
    code += `                        style = MaterialTheme.typography.labelMedium,\n`;
    code += `                        fontWeight = FontWeight.Bold,\n`;
    code += `                        modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp)\n`;
    code += `                    )\n`;
    code += `                }\n`;
    code += `                Text(\n`;
    code += `                    text = "${escapeKotlin(screen.name)}",\n`;
    code += `                    style = MaterialTheme.typography.headlineMedium,\n`;
    code += `                    fontWeight = FontWeight.Bold\n`;
    code += `                )\n`;
    code += `                // Stepper Progress Indicators\n`;
    code += `                Row(\n`;
    code += `                    modifier = Modifier.fillMaxWidth(),\n`;
    code += `                    horizontalArrangement = Arrangement.spacedBy(8.dp),\n`;
    code += `                    verticalAlignment = Alignment.CenterVertically\n`;
    code += `                ) {\n`;
    for (let i = 1; i <= totalSteps; i++) {
      code += `                    FilledIconButton(\n`;
      code += `                        onClick = { onStepChange(${i}) },\n`;
      code += `                        modifier = Modifier.size(36.dp),\n`;
      code += `                        colors = IconButtonDefaults.filledIconButtonColors(\n`;
      code += `                            containerColor = if (wizardStep == ${i}) MaterialTheme.colorScheme.primary else if (wizardStep > ${i}) MaterialTheme.colorScheme.secondaryContainer else MaterialTheme.colorScheme.surfaceVariant\n`;
      code += `                        )\n`;
      code += `                    ) {\n`;
      code += `                        Text("${i}", fontWeight = FontWeight.Bold)\n`;
      code += `                    }\n`;
      if (i < totalSteps) {
        code += `                    LinearProgressIndicator(\n`;
        code += `                        progress = { if (wizardStep > ${i}) 1f else if (wizardStep == ${i}) 0.5f else 0f },\n`;
        code += `                        modifier = Modifier.weight(1f).height(4.dp).clip(CircleShape),\n`;
        code += `                        color = MaterialTheme.colorScheme.primary,\n`;
        code += `                        trackColor = MaterialTheme.colorScheme.surfaceVariant\n`;
        code += `                    )\n`;
      }
    }
    code += `                }\n`;
    code += `            }\n`;
    code += `        }\n\n`;

    code += `        // Wizard Step Content\n`;
    if (screen.steps && screen.steps.length > 0) {
      screen.steps.forEach((st, idx) => {
        code += `        if (wizardStep == ${idx + 1}) {\n`;
        code += `            Column(modifier = Modifier.fillMaxWidth(), verticalArrangement = Arrangement.spacedBy(16.dp)) {\n`;
        code += renderComposeNodes(st.children, 4);
        code += `            }\n`;
        code += `        }\n`;
      });
    } else {
      code += renderComposeNodes(screen.children, 2);
    }

    code += `    }\n`;
    code += `}\n\n`;
    return code;
  }

  // Standard Screen
  code += `    Column(\n`;
  code += `        modifier = Modifier\n`;
  code += `            .fillMaxSize()\n`;
  code += `            .verticalScroll(rememberScrollState())\n`;
  code += `            .padding(16.dp),\n`;
  code += `        verticalArrangement = Arrangement.spacedBy(16.dp)\n`;
  code += `    ) {\n`;
  code += renderComposeNodes(screen.children, 2);
  code += `    }\n`;
  code += `}\n\n`;

  return code;
}

/**
 * Recursively converts Wisp AST nodes into Jetpack Compose Material 3 composables.
 */
function renderComposeNodes(nodes: WispNode[], indentLevel: number): string {
  let out = "";
  const pad = "    ".repeat(indentLevel);

  for (const node of nodes) {
    switch (node.type) {
      case "text": {
        const val = escapeKotlin(node.props.value || "");
        const variant = node.props.variant || "body";
        let style = "MaterialTheme.typography.bodyLarge";
        let fontWeight = "FontWeight.Normal";

        if (variant === "display") {
          style = "MaterialTheme.typography.displayMedium";
          fontWeight = "FontWeight.ExtraBold";
        } else if (variant === "headline") {
          style = "MaterialTheme.typography.headlineMedium";
          fontWeight = "FontWeight.Bold";
        } else if (variant === "title") {
          style = "MaterialTheme.typography.titleLarge";
          fontWeight = "FontWeight.SemiBold";
        } else if (variant === "label") {
          style = "MaterialTheme.typography.labelLarge";
          fontWeight = "FontWeight.Medium";
        } else if (variant === "caption") {
          style = "MaterialTheme.typography.bodySmall";
        }

        let color = "MaterialTheme.colorScheme.onSurface";
        if (node.props.color === "primary") color = "MaterialTheme.colorScheme.primary";
        else if (node.props.color === "secondary") color = "MaterialTheme.colorScheme.secondary";
        else if (node.props.color === "error") color = "MaterialTheme.colorScheme.error";

        out += `${pad}Text(\n`;
        out += `${pad}    text = "${val}",\n`;
        out += `${pad}    style = ${style},\n`;
        out += `${pad}    fontWeight = ${fontWeight},\n`;
        out += `${pad}    color = ${color}\n`;
        out += `${pad})\n`;
        break;
      }

      case "button": {
        const label = escapeKotlin(node.props.label || "Action");
        const variant = node.props.variant || "filled";
        const icon = node.props.icon ? mapComposeIcon(node.props.icon) : null;
        const goto = node.props.goto ? `onNavigate("${escapeKotlin(node.props.goto)}")` : "{ /* click */ }";

        let btnComposable = "Button";
        if (variant === "tonal") btnComposable = "FilledTonalButton";
        else if (variant === "outlined") btnComposable = "OutlinedButton";
        else if (variant === "text") btnComposable = "TextButton";
        else if (variant === "elevated") btnComposable = "ElevatedButton";

        out += `${pad}${btnComposable}(\n`;
        out += `${pad}    onClick = ${goto},\n`;
        out += `${pad}    modifier = Modifier.fillMaxWidth(),\n`;
        out += `${pad}    shape = RoundedCornerShape(20.dp)\n`;
        out += `${pad}) {\n`;
        if (icon) {
          out += `${pad}    Icon(imageVector = ${icon}, contentDescription = null, modifier = Modifier.size(18.dp))\n`;
          out += `${pad}    Spacer(modifier = Modifier.width(8.dp))\n`;
        }
        out += `${pad}    Text("${label}")\n`;
        out += `${pad}}\n`;
        break;
      }

      case "card": {
        const variant = node.props.variant || "elevated";
        let cardFn = "ElevatedCard";
        if (variant === "outlined") cardFn = "OutlinedCard";
        else if (variant === "filled") cardFn = "Card";

        out += `${pad}${cardFn}(\n`;
        out += `${pad}    modifier = Modifier.fillMaxWidth(),\n`;
        out += `${pad}    shape = RoundedCornerShape(24.dp)\n`;
        out += `${pad}) {\n`;
        out += `${pad}    Column(\n`;
        out += `${pad}        modifier = Modifier.padding(20.dp),\n`;
        out += `${pad}        verticalArrangement = Arrangement.spacedBy(12.dp)\n`;
        out += `${pad}    ) {\n`;
        out += renderComposeNodes(node.children, indentLevel + 2);
        out += `${pad}    }\n`;
        out += `${pad}}\n`;
        break;
      }

      case "appbar":
      case "topappbar":
      case "centerappbar": {
        const title = escapeKotlin(node.props.title || "App Title");
        const variant = node.props.variant || "center";
        const icon = mapComposeIcon(node.props.icon || "menu");

        let barName = "CenterAlignedTopAppBar";
        if (variant === "medium") barName = "MediumTopAppBar";
        else if (variant === "large") barName = "LargeTopAppBar";
        else if (variant === "small") barName = "TopAppBar";

        out += `${pad}${barName}(\n`;
        out += `${pad}    title = { Text("${title}", fontWeight = FontWeight.Bold) },\n`;
        out += `${pad}    navigationIcon = {\n`;
        out += `${pad}        IconButton(onClick = { /* menu action */ }) {\n`;
        out += `${pad}            Icon(imageVector = ${icon}, contentDescription = "Menu")\n`;
        out += `${pad}        }\n`;
        out += `${pad}    },\n`;
        out += `${pad}    actions = {\n`;
        out += `${pad}        IconButton(onClick = { /* search */ }) {\n`;
        out += `${pad}            Icon(imageVector = Icons.Default.Search, contentDescription = "Buscar")\n`;
        out += `${pad}        }\n`;
        out += `${pad}        IconButton(onClick = { /* more */ }) {\n`;
        out += `${pad}            Icon(imageVector = Icons.Default.MoreVert, contentDescription = "Más")\n`;
        out += `${pad}        }\n`;
        out += `${pad}    },\n`;
        out += `${pad}    colors = TopAppBarDefaults.topAppBarColors(\n`;
        out += `${pad}        containerColor = MaterialTheme.colorScheme.surfaceContainer\n`;
        out += `${pad}    )\n`;
        out += `${pad})\n`;
        break;
      }

      case "bottomappbar": {
        out += `${pad}BottomAppBar(\n`;
        out += `${pad}    actions = {\n`;
        out += `${pad}        IconButton(onClick = { /* check */ }) { Icon(Icons.Default.Check, contentDescription = null) }\n`;
        out += `${pad}        IconButton(onClick = { /* edit */ }) { Icon(Icons.Default.Edit, contentDescription = null) }\n`;
        out += `${pad}        IconButton(onClick = { /* share */ }) { Icon(Icons.Default.Share, contentDescription = null) }\n`;
        out += `${pad}    },\n`;
        out += `${pad}    floatingActionButton = {\n`;
        out += `${pad}        FloatingActionButton(\n`;
        out += `${pad}            onClick = { /* fab */ },\n`;
        out += `${pad}            containerColor = MaterialTheme.colorScheme.primaryContainer,\n`;
        out += `${pad}            contentColor = MaterialTheme.colorScheme.onPrimaryContainer\n`;
        out += `${pad}        ) {\n`;
        out += `${pad}            Icon(Icons.Default.Add, contentDescription = "Agregar")\n`;
        out += `${pad}        }\n`;
        out += `${pad}    },\n`;
        out += `${pad}    containerColor = MaterialTheme.colorScheme.surfaceContainer\n`;
        out += `${pad})\n`;
        break;
      }

      case "navigationrail":
      case "apprail":
      case "navrail": {
        const hasChildren = node.children && node.children.length > 0;
        const items = hasChildren
          ? node.children
          : [
              { type: "railitem", props: { label: "Inicio", icon: "home" }, children: [] },
              { type: "railitem", props: { label: "Analíticas", icon: "bar-chart-2" }, children: [] },
              { type: "railitem", props: { label: "Ajustes", icon: "settings" }, children: [] },
            ];

        out += `${pad}var selectedRailIndex by remember { mutableIntStateOf(0) }\n`;
        out += `${pad}Row(modifier = Modifier.fillMaxWidth().fillMaxHeight()) {\n`;
        out += `${pad}    NavigationRail(\n`;
        out += `${pad}        modifier = Modifier.fillMaxHeight(),\n`;
        out += `${pad}        containerColor = MaterialTheme.colorScheme.surfaceContainerLow\n`;
        out += `${pad}    ) {\n`;
        if (node.props.fab) {
          const fabIcon = mapComposeIcon(node.props.fab);
          out += `${pad}        FloatingActionButton(\n`;
          out += `${pad}            onClick = { /* fab action */ },\n`;
          out += `${pad}            modifier = Modifier.padding(bottom = 16.dp),\n`;
          out += `${pad}            containerColor = MaterialTheme.colorScheme.primaryContainer\n`;
          out += `${pad}        ) {\n`;
          out += `${pad}            Icon(${fabIcon}, contentDescription = "Acción")\n`;
          out += `${pad}        }\n`;
        }
        items.forEach((item: any, idx: number) => {
          const itemLabel = escapeKotlin(item.props.label || item.props.title || `Item ${idx + 1}`);
          const itemIcon = mapComposeIcon(item.props.icon || "circle");
          out += `${pad}        NavigationRailItem(\n`;
          out += `${pad}            selected = selectedRailIndex == ${idx},\n`;
          out += `${pad}            onClick = { selectedRailIndex = ${idx} },\n`;
          out += `${pad}            icon = { Icon(${itemIcon}, contentDescription = "${itemLabel}") },\n`;
          out += `${pad}            label = { Text("${itemLabel}") }\n`;
          out += `${pad}        )\n`;
        });
        out += `${pad}    }\n`;

        if (hasChildren && node.children.some((c: any) => c.children && c.children.length > 0)) {
          out += `${pad}    Box(modifier = Modifier.weight(1f).fillMaxHeight().padding(16.dp)) {\n`;
          out += `${pad}        when (selectedRailIndex) {\n`;
          node.children.forEach((c: any, idx: number) => {
            out += `${pad}            ${idx} -> Column(modifier = Modifier.fillMaxWidth(), verticalArrangement = Arrangement.spacedBy(16.dp)) {\n`;
            if (c.children && c.children.length > 0) {
              out += renderComposeNodes(c.children, indentLevel + 4);
            } else {
              out += `${pad}                Text("${escapeKotlin(c.props.label || c.props.title || "Contenido")}", style = MaterialTheme.typography.titleMedium)\n`;
            }
            out += `${pad}            }\n`;
          });
          out += `${pad}        }\n`;
          out += `${pad}    }\n`;
        }
        out += `${pad}}\n`;
        break;
      }

      case "textfield": {
        const name = escapeKotlin(node.props.name || "input");
        const label = escapeKotlin(node.props.label || name);
        const icon = node.props.icon ? mapComposeIcon(node.props.icon) : null;

        out += `${pad}var text_${name} by remember { mutableStateOf("") }\n`;
        out += `${pad}OutlinedTextField(\n`;
        out += `${pad}    value = text_${name},\n`;
        out += `${pad}    onValueChange = { text_${name} = it; formData["${name}"] = it },\n`;
        out += `${pad}    label = { Text("${label}") },\n`;
        if (icon) {
          out += `${pad}    leadingIcon = { Icon(${icon}, contentDescription = null) },\n`;
        }
        out += `${pad}    shape = RoundedCornerShape(16.dp),\n`;
        out += `${pad}    modifier = Modifier.fillMaxWidth()\n`;
        out += `${pad})\n`;
        break;
      }

      case "progress":
      case "loading":
      case "spinner":
      case "linearprogress":
      case "circularprogress": {
        const isCircular = node.type === "circularprogress" || node.type === "spinner" || node.props.variant === "circular";
        const val = node.props.value !== undefined ? Number(node.props.value) / 100 : 0.7;

        if (isCircular) {
          out += `${pad}Box(modifier = Modifier.fillMaxWidth(), contentAlignment = Alignment.Center) {\n`;
          out += `${pad}    CircularProgressIndicator(\n`;
          out += `${pad}        progress = { ${val}f },\n`;
          out += `${pad}        strokeWidth = 6.dp,\n`;
          out += `${pad}        color = MaterialTheme.colorScheme.primary,\n`;
          out += `${pad}        trackColor = MaterialTheme.colorScheme.surfaceVariant\n`;
          out += `${pad}    )\n`;
          out += `${pad}}\n`;
        } else {
          out += `${pad}Column(modifier = Modifier.fillMaxWidth(), verticalArrangement = Arrangement.spacedBy(6.dp)) {\n`;
          if (node.props.label) {
            out += `${pad}    Text("${escapeKotlin(node.props.label)}", style = MaterialTheme.typography.labelMedium)\n`;
          }
          out += `${pad}    LinearProgressIndicator(\n`;
          out += `${pad}        progress = { ${val}f },\n`;
          out += `${pad}        modifier = Modifier.fillMaxWidth().height(8.dp).clip(RoundedCornerShape(4.dp)),\n`;
          out += `${pad}        color = MaterialTheme.colorScheme.primary,\n`;
          out += `${pad}        trackColor = MaterialTheme.colorScheme.surfaceVariant\n`;
          out += `${pad}    )\n`;
          out += `${pad}}\n`;
        }
        break;
      }

      case "switch": {
        const name = escapeKotlin(node.props.name || node.id);
        const label = escapeKotlin(node.props.label || name);
        const checked = node.props.checked === true;

        out += `${pad}var switch_${name} by remember { mutableStateOf(${checked}) }\n`;
        out += `${pad}Row(\n`;
        out += `${pad}    modifier = Modifier.fillMaxWidth().padding(vertical = 4.dp),\n`;
        out += `${pad}    horizontalArrangement = Arrangement.SpaceBetween,\n`;
        out += `${pad}    verticalAlignment = Alignment.CenterVertically\n`;
        out += `${pad}) {\n`;
        out += `${pad}    Text("${label}", style = MaterialTheme.typography.bodyLarge)\n`;
        out += `${pad}    Switch(\n`;
        out += `${pad}        checked = switch_${name},\n`;
        out += `${pad}        onCheckedChange = { switch_${name} = it; formData["${name}"] = it }\n`;
        out += `${pad}    )\n`;
        out += `${pad}}\n`;
        break;
      }

      case "checkbox": {
        const name = escapeKotlin(node.props.name || node.id);
        const label = escapeKotlin(node.props.label || name);
        const checked = node.props.checked === true;

        out += `${pad}var check_${name} by remember { mutableStateOf(${checked}) }\n`;
        out += `${pad}Row(\n`;
        out += `${pad}    modifier = Modifier.fillMaxWidth().clickable { check_${name} = !check_${name}; formData["${name}"] = check_${name} },\n`;
        out += `${pad}    verticalAlignment = Alignment.CenterVertically,\n`;
        out += `${pad}    horizontalArrangement = Arrangement.spacedBy(8.dp)\n`;
        out += `${pad}) {\n`;
        out += `${pad}    Checkbox(\n`;
        out += `${pad}        checked = check_${name},\n`;
        out += `${pad}        onCheckedChange = { check_${name} = it; formData["${name}"] = it }\n`;
        out += `${pad}    )\n`;
        out += `${pad}    Text("${label}", style = MaterialTheme.typography.bodyMedium)\n`;
        out += `${pad}}\n`;
        break;
      }

      case "slider": {
        const name = escapeKotlin(node.props.name || "slider");
        const min = Number(node.props.min) || 0;
        const max = Number(node.props.max) || 100;
        const val = Number(node.props.value) || 50;

        out += `${pad}var slider_${name} by remember { mutableFloatStateOf(${val}f) }\n`;
        out += `${pad}Column(modifier = Modifier.fillMaxWidth()) {\n`;
        out += `${pad}    Text("${escapeKotlin(node.props.label || name)}: \${slider_${name}.toInt()}", style = MaterialTheme.typography.labelMedium)\n`;
        out += `${pad}    Slider(\n`;
        out += `${pad}        value = slider_${name},\n`;
        out += `${pad}        onValueChange = { slider_${name} = it; formData["${name}"] = it },\n`;
        out += `${pad}        valueRange = ${min}f..${max}f\n`;
        out += `${pad}    )\n`;
        out += `${pad}}\n`;
        break;
      }

      case "chip": {
        const label = escapeKotlin(node.props.label || "Chip");
        const icon = node.props.icon ? mapComposeIcon(node.props.icon) : null;

        out += `${pad}var chipSelected_${node.id} by remember { mutableStateOf(${node.props.selected === true}) }\n`;
        out += `${pad}FilterChip(\n`;
        out += `${pad}    selected = chipSelected_${node.id},\n`;
        out += `${pad}    onClick = { chipSelected_${node.id} = !chipSelected_${node.id} },\n`;
        out += `${pad}    label = { Text("${label}") },\n`;
        if (icon) {
          out += `${pad}    leadingIcon = { Icon(${icon}, contentDescription = null, modifier = Modifier.size(16.dp)) },\n`;
        }
        out += `${pad}    shape = RoundedCornerShape(12.dp)\n`;
        out += `${pad})\n`;
        break;
      }

      case "listitem": {
        const title = escapeKotlin(node.props.title || node.props.label || "Elemento");
        const subtitle = node.props.subtitle ? escapeKotlin(node.props.subtitle) : null;
        const icon = node.props.icon ? mapComposeIcon(node.props.icon) : null;

        out += `${pad}ListItem(\n`;
        out += `${pad}    headlineContent = { Text("${title}", fontWeight = FontWeight.SemiBold) },\n`;
        if (subtitle) {
          out += `${pad}    supportingContent = { Text("${subtitle}") },\n`;
        }
        if (icon) {
          out += `${pad}    leadingContent = { Icon(${icon}, contentDescription = null, tint = MaterialTheme.colorScheme.primary) },\n`;
        }
        out += `${pad}    trailingContent = { Icon(Icons.AutoMirrored.Filled.ArrowForward, contentDescription = null, modifier = Modifier.size(16.dp)) }\n`;
        out += `${pad})\n`;
        break;
      }

      case "divider": {
        out += `${pad}HorizontalDivider(modifier = Modifier.padding(vertical = 8.dp), color = MaterialTheme.colorScheme.outlineVariant)\n`;
        break;
      }

      case "spacer": {
        const h = Number(node.props.size || node.props.height || 16);
        out += `${pad}Spacer(modifier = Modifier.height(${h}.dp))\n`;
        break;
      }

      case "fab": {
        const label = node.props.label ? escapeKotlin(node.props.label) : null;
        const icon = mapComposeIcon(node.props.icon || "plus");

        if (label) {
          out += `${pad}ExtendedFloatingActionButton(\n`;
          out += `${pad}    onClick = { /* fab click */ },\n`;
          out += `${pad}    icon = { Icon(${icon}, contentDescription = null) },\n`;
          out += `${pad}    text = { Text("${label}") },\n`;
          out += `${pad}    containerColor = MaterialTheme.colorScheme.primaryContainer,\n`;
          out += `${pad}    contentColor = MaterialTheme.colorScheme.onPrimaryContainer\n`;
          out += `${pad})\n`;
        } else {
          out += `${pad}FloatingActionButton(\n`;
          out += `${pad}    onClick = { /* fab click */ },\n`;
          out += `${pad}    containerColor = MaterialTheme.colorScheme.primaryContainer,\n`;
          out += `${pad}    contentColor = MaterialTheme.colorScheme.onPrimaryContainer\n`;
          out += `${pad}) {\n`;
          out += `${pad}    Icon(${icon}, contentDescription = null)\n`;
          out += `${pad}}\n`;
        }
        break;
      }

      case "row": {
        out += `${pad}Row(\n`;
        out += `${pad}    modifier = Modifier.fillMaxWidth(),\n`;
        out += `${pad}    horizontalArrangement = Arrangement.spacedBy(12.dp),\n`;
        out += `${pad}    verticalAlignment = Alignment.CenterVertically\n`;
        out += `${pad}) {\n`;
        out += renderComposeNodes(node.children, indentLevel + 1);
        out += `${pad}}\n`;
        break;
      }

      case "column": {
        out += `${pad}Column(\n`;
        out += `${pad}    modifier = Modifier.fillMaxWidth(),\n`;
        out += `${pad}    verticalArrangement = Arrangement.spacedBy(12.dp)\n`;
        out += `${pad}) {\n`;
        out += renderComposeNodes(node.children, indentLevel + 1);
        out += `${pad}}\n`;
        break;
      }

      default: {
        if (node.children && node.children.length > 0) {
          out += `${pad}Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {\n`;
          out += renderComposeNodes(node.children, indentLevel + 1);
          out += `${pad}}\n`;
        }
        break;
      }
    }
  }

  return out;
}
