/**
 * Escapes Kotlin string literals
 */
function escapeKotlin(str: string): string {
  return String(str || "")
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\$/g, "\\$");
}

/**
 * Capitalizes a string to PascalCase for Kotlin Composable names
 */
function toPascalCase(str: string): string {
  return (str || "Main")
    .replace(/[^a-zA-Z0-9]/g, " ")
    .split(" ")
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join("") || "Screen";
}

/**
 * Maps icon name to standard Material Icon Vector in Jetpack Compose
 */
function mapComposeIcon(name?: string): string {
  const n = (name || "star").toLowerCase();
  if (n.includes("user") || n.includes("person") || n.includes("account")) return "Icons.Default.Person";
  if (n.includes("home")) return "Icons.Default.Home";
  if (n.includes("search")) return "Icons.Default.Search";
  if (n.includes("setting")) return "Icons.Default.Settings";
  if (n.includes("bell") || n.includes("notif")) return "Icons.Default.Notifications";
  if (n.includes("mail") || n.includes("email")) return "Icons.Default.Email";
  if (n.includes("lock") || n.includes("key")) return "Icons.Default.Lock";
  if (n.includes("check")) return "Icons.Default.Check";
  if (n.includes("add") || n.includes("plus")) return "Icons.Default.Add";
  if (n.includes("arrow-right") || n.includes("forward")) return "Icons.AutoMirrored.Filled.ArrowForward";
  if (n.includes("arrow-left") || n.includes("back")) return "Icons.AutoMirrored.Filled.ArrowBack";
  if (n.includes("close") || n.includes("clear") || n.includes("x")) return "Icons.Default.Close";
  if (n.includes("menu")) return "Icons.Default.Menu";
  if (n.includes("edit")) return "Icons.Default.Edit";
  if (n.includes("delete") || n.includes("trash")) return "Icons.Default.Delete";
  if (n.includes("refresh")) return "Icons.Default.Refresh";
  if (n.includes("info")) return "Icons.Default.Info";
  if (n.includes("warning") || n.includes("alert")) return "Icons.Default.Warning";
  if (n.includes("star") || n.includes("fav")) return "Icons.Default.Star";
  if (n.includes("share")) return "Icons.Default.Share";
  if (n.includes("filter")) return "Icons.Default.FilterList";
  if (n.includes("time") || n.includes("clock")) return "Icons.Default.DateRange";
  return "Icons.Default.Star";
}

